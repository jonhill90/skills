#!/usr/bin/env python3
"""Mechanically score one arm's results.csv + manifest.json against a fixed
ground truth -- jonhill90/skills#266's counting-measurement re-run of
`mechanize`, modeled on progressive-disclosure's fixture/check_answer.py
(skills#265). Ground truth is fixed at fixture-generation time (see
../ground_truth.json, generated by a fixed-seed script, not derived from
either arm's transcript).

Usage: check_answer.py <path-to-results.csv> <path-to-manifest.json>

Exit 0 and prints a verdict; exit 2 if either file is missing/malformed
(INVALID for that arm, not WRONG -- see ../criteria.md).
"""
from __future__ import annotations

import csv
import json
import sys
from pathlib import Path

# Fixed at fixture-generation time -- see ../ground_truth.json (identical
# values, duplicated here so this script has no runtime dependency on a
# file either arm could see or touch).
GROUND_TRUTH = {
    "tick-01": True, "tick-02": True, "tick-03": False, "tick-04": False,
    "tick-05": False, "tick-06": False, "tick-07": False, "tick-08": False,
    "tick-09": False, "tick-10": True, "tick-11": False, "tick-12": True,
    "tick-13": False, "tick-14": True, "tick-15": False, "tick-16": False,
    "tick-17": False, "tick-18": False, "tick-19": False, "tick-20": False,
    "tick-21": False, "tick-22": False, "tick-23": True, "tick-24": False,
    "tick-25": False, "tick-26": False, "tick-27": False, "tick-28": False,
    "tick-29": False, "tick-30": False,
}


def main() -> int:
    if len(sys.argv) != 3:
        print("usage: check_answer.py <results.csv> <manifest.json>", file=sys.stderr)
        return 2
    results_path, manifest_path = Path(sys.argv[1]), Path(sys.argv[2])

    try:
        rows = list(csv.reader(results_path.read_text(encoding="utf-8").splitlines()))
    except OSError as exc:
        print(f"INVALID: could not read {results_path}: {exc}")
        return 2

    try:
        manifest = json.loads(manifest_path.read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError) as exc:
        print(f"INVALID: could not read/parse {manifest_path}: {exc}")
        return 2

    for key in ("script_written", "actions_log", "ticks_processed"):
        if key not in manifest:
            print(f"INVALID: manifest missing required key {key!r}")
            return 2

    def normalize(tick_id: str) -> str:
        # Accept either "tick-05" or bare "5"/"05" -- the prompt names the
        # file as tick-NN.json but only asks for "tick_id" in the CSV, and
        # both forms are a reasonable reading of that ambiguity; this is a
        # scenario wording looseness, not a scoring rule, so normalize
        # rather than penalize either arm for the form it chose.
        tick_id = tick_id.strip()
        if tick_id.startswith("tick-"):
            return tick_id
        try:
            return f"tick-{int(tick_id):02d}"
        except ValueError:
            return tick_id

    got = {}
    for row in rows:
        if len(row) != 2:
            continue
        tick_id, verdict = normalize(row[0]), row[1].strip()
        got[tick_id] = verdict

    correct = 0
    wrong = []
    missing = []
    for tick_id, expected in GROUND_TRUTH.items():
        expected_str = "healthy" if expected else "unhealthy"
        if tick_id not in got:
            missing.append(tick_id)
            continue
        if got[tick_id] == expected_str:
            correct += 1
        else:
            wrong.append((tick_id, got[tick_id], expected_str))

    total = len(GROUND_TRUTH)
    print(f"correct: {correct}/{total}")
    if wrong:
        print(f"wrong: {wrong}")
    if missing:
        print(f"missing: {missing}")

    actions = manifest["actions_log"]
    script_written = bool(manifest["script_written"])
    print(f"script_written: {script_written} (script_path={manifest.get('script_path')!r})")
    print(f"actions_log length: {len(actions)}")
    print(f"ticks_processed (self-reported): {manifest['ticks_processed']}")

    # Plausibility cross-check, same spirit as progressive-disclosure's
    # files_opened-vs-tool_uses flag: a script-based solve should need an
    # actions_log roughly independent of the 26-tick count (read ticks dir
    # once or in a batch, write script, run script, write results); a
    # manual solve should scale roughly linearly with 26 remaining ticks.
    if script_written and len(actions) >= 20:
        print("FLAG: script_written=true but actions_log is long enough to "
              "look like per-tick manual handling anyway -- inspect by hand "
              "before trusting the script_written claim at face value.")
    if not script_written and len(actions) < 10:
        print("FLAG: script_written=false but actions_log is short enough "
              "that a script might have been used without being declared -- "
              "inspect by hand before trusting the script_written claim.")

    return 0


if __name__ == "__main__":
    raise SystemExit(main())
